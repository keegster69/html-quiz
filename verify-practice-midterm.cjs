const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
assert(fs.existsSync('biology-practice-midterm.html'), 'Standalone midterm page exists');
const page = fs.readFileSync('biology-practice-midterm.html','utf8');
const start = page.indexOf('const practiceQuestions=')+'const practiceQuestions='.length;
const questions = JSON.parse(page.slice(start,page.indexOf(';\n',start)));
assert.deepEqual(questions.map(q=>q.number),Array.from({length:40},(_,i)=>i+1).filter(n=>![3,8,23,32].includes(n)));
assert.equal(questions.filter(q=>q.correct).length,36);
assert.deepEqual(questions.filter(q=>!q.correct).map(q=>q.number),[]);
assert.equal(questions.find(q=>q.number===31).correct,'d');
assert.equal(questions.find(q=>q.number===36).correct,'d');
assert(questions.find(q=>q.number===34).prompt.includes('-35. What is true'), 'Negative promoter coordinates must not split questions');
assert(questions.find(q=>q.number===18).prompt.includes('iv. DNA double helix'));
assert(questions.every(q=>q.options.length===4 && (!q.correct || q.options.some(o=>o.id===q.correct))));
assert(page.includes('var Ei="biol130-midterm/"'));
assert(page.includes('const sourceQuestionCount=40;'));
assert(page.includes('const missingQuestionNumbers=[];'));
for(const m of page.matchAll(/<script[^>]*>([\s\S]*?)<\/script>/g))new vm.Script(m[1]);
const nav=fs.readFileSync('biology-review.html','utf8').match(/<nav\b[^>]*>[\s\S]*?<\/nav>/)[0];
assert(nav.indexOf('biology-practice-midterm.html')<nav.indexOf('biology-practice-exam.html'));
assert(nav.includes('flex-direction:column'));
console.log('PASS: 36 scored midterm questions; Q31 = D; independent storage, navigation, and JavaScript syntax valid.');
